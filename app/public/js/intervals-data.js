const INTERVAL_KEYS = Object.keys(INTERVALS_DATA);

function getRandomInterval() {
    const key = INTERVAL_KEYS[Math.floor(Math.random() * INTERVAL_KEYS.length)];
    return { key: key, data: INTERVALS_DATA[key] };
}

function getRandomPair(intervalKey) {
    const data = INTERVALS_DATA[intervalKey];
    if (!data) return null;
    return data.pairs[Math.floor(Math.random() * data.pairs.length)];
}

function shuffleArray(arr) {
    const shuffled = [...arr];
    for (let i = shuffled.length - 1; i > 0; i--) {
        const j = Math.floor(Math.random() * (i + 1));
        [shuffled[i], shuffled[j]] = [shuffled[j], shuffled[i]];
    }
    return shuffled;
}